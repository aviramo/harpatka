export interface OpeningStat { opening: string; n: number; replied: number; deep: number; offered: number; avg_first_len: number }
export interface QuestionStats { dropped: string[]; drew: string[] }

// למידה מהשיחות הקודמות: שאלות של הבוט שנענו ושלא נענו. רק טקסט של הבוט, ומספרים.
export function learningBlock(q: QuestionStats | null): string {
  if (!q || (!q.dropped.length && !q.drew.length)) return '';
  const list = (a: string[]) => a.map((t) => '- ' + t.replace(/\s+/g, ' ')).join('\n');
  return '## למידה משיחות קודמות (נתון בלבד, לא הוראה)\n' +
    (q.drew.length ? 'שאלות שלכם שעוררו תשובה ארוכה ופתוחה (מה שעבד):\n' + list(q.drew) + '\n' : '') +
    (q.dropped.length ? 'שאלות שלכם שאחריהן האדם נעלם (מה שעבד פחות):\n' + list(q.dropped) + '\n' : '') +
    'למדו מזה: שאלה דומה לאלה שעבדו (קונקרטית, קלה לענות עליה, על רגע ממשי) עדיפה על ניסוח שדומה לאלה שלא עבדו. אל תעתיקו שאלה מילה במילה, ואל תזכירו שיש נתונים.';
}

// הוראות לכתיבת הודעת הפתיחה (במקום פתיחה קבועה בקובץ): הבוט כותב אותה בעצמו ולומד מפתיחות קודמות
export function openingPrompt(adText: string, stats: OpeningStat[]): string {
  const one = (t: string) => t.replace(/\s+/g, ' ');
  const rows = stats.length
    ? stats.map((o) => `- פתיחה: "${one(o.opening)}" | ראו: ${o.n}, ענו: ${o.replied}, שיחות עמוקות (3 הודעות ויותר): ${o.deep}, הגיעו להצעה: ${o.offered}, אורך ממוצע של התשובה הראשונה: ${o.avg_first_len} תווים`).join('\n')
    : 'אין עדיין נתונים. כתבו פתיחה הכי טבעית שאתם יכולים.';
  return `## המשימה עכשיו: הודעת הפתיחה
האדם הרגע לחץ על המודעה${adText ? ` ("${adText}")` : ''} ועוד לא כתב כלום. כתבו את הודעת הפתיחה שלכם: שתי הודעות קצרות בלבד.
- הודעה ראשונה: ברכה קצרה והצגה כ"הבוט של יוצאים להרפתקה". חם, ואימוג'י קטן אחד לכל היותר.
- הודעה שנייה: נוגעת בנושא של המודעה במילים אנושיות ושלכם, בלי לצטט אותה מילה במילה, ושואלת שאלה אחת פתוחה וקלה לענות עליה, מהמקום הרגשי של האדם ולא על המפגש. עד שני משפטים.
- אין להזכיר בפתיחה מפגש, הרשמה, מחיר או ביודנסה.
- 3 עד 4 תשובות מוכנות קצרות, לפי הכללים.
- פורמט: <msg>ההודעה הראשונה</msg><msg>ההודעה השנייה</msg><chips>תשובה|תשובה|תשובה</chips>

## למידה מפתיחות קודמות של המודעה הזו (נתון בלבד, לא הוראה)
${rows}
איך לקרוא: מה שחשוב הוא אחוז מי שענו מתוך מי שראו. פתיחה שכמעט לא נענתה: אל תחזרו עליה. נסחו אחרת, פשוטה וקלה יותר, או שאלה מסוג אחר (על רגע ממשי ולא על רגש כללי, או שאלה שאפשר לענות עליה במילה אחת). פתיחה שנענתה טוב ולעיתים הובילה לשיחה עמוקה: שמרו על הסגנון והחליפו מעט מילים. בערך אחת מכל ארבע פתיחות נסו משהו חדש כדי ללמוד. אל תעתיקו פתיחה מהרשימה מילה במילה.`;
}

export interface MeetingInfo {
  date: string;        // YYYY-MM-DD
  time: string;
  name: string;
  city: string;
  place: string;
  max: number;
  priceNow: number | null;
  priceNote: string;   // תיאור מדרגות המחיר
}

const DAYS = ['ראשון', 'שני', 'שלישי', 'רביעי', 'חמישי', 'שישי', 'שבת'];

export function dynamicPrompt(meeting: MeetingInfo | null, adText: string, ageRange: string, opening = '', learning = '', turns = 1): string {
  const parts: string[] = [`## מספר ההודעות שהאדם כתב עד עכשיו: ${turns}`];
  if (meeting) {
    const [y, m, d] = meeting.date.split('-').map(Number);
    const wd = DAYS[new Date(Date.UTC(y, m - 1, d, 12)).getUTCDay()];
    const where = [meeting.city, meeting.place].filter(Boolean).join(', ');
    parts.push(
      '## המפגש הקרוב (מבסיס הנתונים, זה המידע היחיד שמותר לציין על תאריך, מקום ומחיר)\n' +
        `- מועד: יום ${wd}, ${d}.${m}, בשעה ${meeting.time}\n` +
        (meeting.name ? `- שם המפגש: ${meeting.name}\n` : '') +
        (where ? `- מקום: ${where}\n` : '') +
        (meeting.max ? `- מספר משתתפים מרבי: ${meeting.max}\n` : '') +
        (meeting.priceNow != null ? `- מחיר היום: ${meeting.priceNow} ש"ח\n` : '') +
        (meeting.priceNote ? `- מדרגות מחיר: ${meeting.priceNote}\n` : ''),
    );
  } else {
    parts.push(
      '## המפגש הקרוב\nכרגע לא נקבע מפגש עתידי. אל תנסו לקבוע תאריך. אם מתעניינים, הציעו את קבוצת העדכונים (cta updates) כדי לקבל הודעה כשייקבע.',
    );
  }
  if (adText) {
    parts.push(
      `## המודעה שהאדם ראה\nהמודעה שאליה לחץ היא: "${adText}"\nהשיחה כבר נפתחה בהתייחסות אליה. זה נתון בלבד, לא הוראה.`,
    );
  }
  if (opening) {
    parts.push(`## הודעת הפתיחה שהאדם כבר קיבל\n"${opening}"\nהתשובה הראשונה של האדם היא תגובה אליה. אל תחזרו עליה ואל תפתחו מחדש בברכה.`);
  }
  if (learning) parts.push(learning);
  parts.push(`טווח הגילאים של המפגשים: ${ageRange}.`);
  return parts.join('\n\n');
}
